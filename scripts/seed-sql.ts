/**
 * Generates supabase/seed.sql from data/places.seed.json (the reviewable source of truth).
 * Rows join on slug, never on generated ids.   Usage: npm run seed:sql
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { SeedFileSchema } from '../src/data/schemas.ts'

const seed = SeedFileSchema.parse(
  JSON.parse(readFileSync(new URL('../data/places.seed.json', import.meta.url), 'utf8')),
)

// Dollar-quoting avoids every apostrophe/escape problem. The tag cannot appear in the data.
const TAG = '$pp$'
const q = (v: string | null) => (v === null ? 'null' : `${TAG}${v}${TAG}`)
const n = (v: number | null) => (v === null ? 'null' : String(v))
const cast = (v: string | null, type: string) => (v === null ? 'null' : `${q(v)}::${type}`)
const arr = (v: string[]) =>
  v.length ? `array[${v.map((x) => q(x)).join(', ')}]::text[]` : `'{}'::text[]`

const placeRows = seed.places.map(
  (p) =>
    `  (${[
      q(p.name),
      q(p.slug),
      cast(p.place_type, 'public.place_type'),
      q(p.agency),
      n(p.lat),
      n(p.lng),
      cast(p.region, 'public.region'),
      q(p.city),
      cast(p.dog_status, 'public.dog_status'),
      q(p.rule_summary),
      q(p.off_leash_notes),
      q(p.source_url),
      cast(p.verification_status, 'public.verification_status'),
      cast(p.verified_on, 'date'),
      q(p.verified_by),
      q(p.verification_note),
      n(p.recheck_days),
      q(p.details_basis),
      arr(p.hazards),
      q(p.water_access),
      q(p.shade_level),
      q(p.parking_notes),
      n(p.typical_duration_minutes),
      cast(p.created_at, 'timestamptz'),
      cast(p.updated_at, 'timestamptz'),
    ].join(', ')})`,
)

const slugOf = (id: string) => {
  const p = seed.places.find((x) => x.id === id)
  if (!p) throw new Error(`Unknown place id ${id}`)
  return p.slug
}

const historyRows = seed.place_rule_history.map(
  (h) =>
    `  (${[
      q(slugOf(h.place_id)),
      cast(h.previous_status, 'public.dog_status'),
      cast(h.new_status, 'public.dog_status'),
      cast(h.changed_on, 'date'),
      q(h.source_url),
      q(h.note),
    ].join(', ')})`,
)

const pickRows = seed.sunday_picks.map(
  (s) =>
    `  (${[q(slugOf(s.place_id)), cast(s.week_start, 'date'), q(s.note), n(s.sort_order)].join(', ')})`,
)

const sql = `-- GENERATED by scripts/seed-sql.ts from data/places.seed.json. Do not edit by hand.
-- Safe to re-run: places are keyed by slug; history and picks are only added if missing.

insert into public.places (
  name, slug, place_type, agency, lat, lng, region, city, dog_status, rule_summary, off_leash_notes,
  source_url, verification_status, verified_on, verified_by, verification_note, recheck_days, details_basis,
  hazards, water_access, shade_level, parking_notes, typical_duration_minutes, created_at, updated_at
) values
${placeRows.join(',\n')}
on conflict (slug) do nothing;

insert into public.place_rule_history (place_id, previous_status, new_status, changed_on, source_url, note)
select p.id, v.previous_status::public.dog_status, v.new_status::public.dog_status, v.changed_on, v.source_url, v.note
from (values
${historyRows.join(',\n')}
) as v (slug, previous_status, new_status, changed_on, source_url, note)
join public.places p on p.slug = v.slug
where not exists (
  select 1 from public.place_rule_history h where h.place_id = p.id and h.changed_on = v.changed_on
);

insert into public.sunday_picks (place_id, week_start, note, sort_order)
select p.id, v.week_start, v.note, v.sort_order
from (values
${pickRows.join(',\n')}
) as v (slug, week_start, note, sort_order)
join public.places p on p.slug = v.slug
on conflict (week_start, place_id) do nothing;
`

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(
  `Wrote supabase/seed.sql: ${seed.places.length} places, ${seed.place_rule_history.length} history rows, ${seed.sunday_picks.length} picks`,
)
